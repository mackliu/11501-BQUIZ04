<?php
// =============================================================================
// 檔案：captcha_verify.php
// 用途：【服務二】檢查使用者輸入的圖形驗證碼對不對
// 方法：只接受 POST
// 格式：回傳純文字的 1（正確）或 0（不符合），不是 JSON
// =============================================================================
//
// ■ 使用說明 ────────────────────────────────────────────────────────────────
//
//   送出方式有兩種，這支服務兩種都吃：
//
//   (A) 一般表單格式（application/x-www-form-urlencoded）
//         POST captcha_verify.php
//         Body: captcha=g8RsLJ
//
//   (B) JSON 格式（application/json）
//         POST captcha_verify.php
//         Body: {"captcha":"g8RsLJ"}
//
//   回傳內容永遠只有一個字元：
//         1  →  驗證碼正確
//         0  →  不符合（打錯、沒填、Session 過期、或用錯請求方法）
//
//   之所以回傳單純的 1 / 0 而不是 JSON，是因為前端只需要「對或不對」，
//   用 response.text() 接下來判斷一次就好，不必解析 JSON，也不用怕格式對不上。
//
// ■ 前端呼叫範例 ─────────────────────────────────────────────────────────────
//
//   async function checkCaptcha() {
//       const response = await fetch('captcha_verify.php', {
//           method: 'POST',
//           credentials: 'same-origin',                        // ★ 必須，理由見下
//           headers: { 'Content-Type': 'application/json' },
//           body: JSON.stringify({ captcha: 使用者輸入的字串 })
//       });
//       const result = (await response.text()).trim();          // 拿到 '1' 或 '0'
//       if (result === '1') {
//           // 驗證通過，可以繼續送出表單
//       } else {
//           // 驗證失敗，提示使用者重打，或呼叫 captcha_image.php?reload=1 換一張
//       }
//   }
//
//   ★ credentials: 'same-origin' 為什麼必須加？
//     正確答案存在伺服器的 Session 裡，伺服器是靠 Cookie 中的 PHPSESSID
//     來認出「你就是剛才來要驗證碼的那個人」。
//     沒有這個選項，fetch 不會帶 Cookie，伺服器會當成全新的訪客，
//     Session 裡當然沒有答案，於是永遠回傳 0。
//     這是驗證碼改成 ajax 後最常見的失敗原因，遇到「怎麼打都是 0」先檢查這裡。
//
//   ★ 拿到 '1' 之後要記得：
//     前端的判斷只是為了給使用者即時的畫面回饋，不能當作真正的防線
//     （任何人都可以繞過前端，直接對你的表單處理程式送資料）。
//     真正要保護的那支程式（例如處理註冊、留言的後端），
//     必須自己再呼叫一次 captchaVerify() 確認，不能只信前端說「我驗過了」。
//
// ■ 重要行為說明：驗證後不會清掉答案 ─────────────────────────────────────────
//
//   這支服務「不會」在驗證完之後把 Session 裡的驗證碼刪掉。
//   好處：使用者打錯字時可以直接重打，不必每錯一次就換一張新圖，體驗比較好。
//   代價：同一組驗證碼可以被無限次嘗試，擋不住程式暴力猜測。
//
//   要換題請由前端另外呼叫 captcha_image.php?reload=1。
//
//   如果這套機制要用在正式對外的網站，建議補上以下其中一項：
//     - 記錄失敗次數，超過 N 次（例如 5 次）就在伺服器端強制換一組新驗證碼
//     - 驗證成功後立刻 unset($_SESSION[CAPTCHA_SESSION_KEY])，讓每組答案只能用一次
//       （但要注意：這樣一來同一組驗證碼就不能重複驗證，前端流程要配合調整）
// =============================================================================


// 載入共用函式庫，取得 captchaVerify() 這個比對函式。
// 比對的細節（去頭尾空白、忽略大小寫、防 timing attack）全部寫在函式庫裡，
// 這支服務只負責「收資料 → 呼叫比對 → 輸出結果」這三件事。
require_once 'captcha_lib.php';


// -----------------------------------------------------------------------------
// 送出 HTTP 回應標頭
// -----------------------------------------------------------------------------
// 回傳的是純文字（就一個 1 或 0），所以型別宣告成 text/plain。
// 如果誤寫成 text/html，瀏覽器會嘗試把它當網頁解析，雖然多半沒事，
// 但正確標示型別是後端服務該有的基本禮貌。
header('Content-Type: text/plain; charset=utf-8');

// 驗證結果絕對不能被快取。
// 想像一下：使用者第一次打錯得到 0，如果這個回應被快取起來，
// 第二次打對了瀏覽器卻直接把快取的 0 拿出來用，那就永遠過不了關。
header('Cache-Control: no-store, no-cache, must-revalidate');


// -----------------------------------------------------------------------------
// 檢查請求方法：這支服務只接受 POST
// -----------------------------------------------------------------------------
// 為什麼驗證一定要用 POST，不能用 GET？
//   1. 用 GET 的話，使用者輸入的答案會出現在網址列上，
//      並且被瀏覽器的歷史紀錄、伺服器的存取日誌一起記下來
//   2. GET 的網址容易被瀏覽器快取或被使用者收藏、分享
//   3. 語意上 GET 代表「查詢資料」、POST 代表「送出資料做處理」，
//      驗證屬於後者
if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
    http_response_code(405); // 405 = Method Not Allowed（方法不被允許）

    // 注意這裡仍然輸出 '0'。
    // 這是刻意的設計：讓前端的判斷邏輯永遠只要處理 '1' 和「其他」兩種情況，
    // 不會因為呼叫方式寫錯，就收到一段預期外的錯誤訊息而誤判成通過。
    echo '0';
    exit;
}


// -----------------------------------------------------------------------------
// 讀取使用者送來的答案（同時支援 JSON 和一般表單兩種格式）
// -----------------------------------------------------------------------------
// PHP 的 $_POST 只會自動填好「一般表單格式」的資料。
// 前端用 JSON.stringify() 送 JSON 時，$_POST 會是空的，
// 資料在原始的請求內容（request body）裡，必須自己讀出來解析。

// php://input 是一個特殊的位址，代表「這次請求的原始 body 內容」。
// file_get_contents() 平常是用來讀檔案的，這裡用它把 body 整個讀成字串。
$rawBody = file_get_contents('php://input');

// json_decode() 把 JSON 字串轉成 PHP 資料。
// 第二個參數 true 代表「轉成關聯陣列」，不加的話會轉成物件，取值要用 -> 比較麻煩。
// 如果 body 根本不是合法的 JSON（例如它是一般表單格式），這裡會回傳 null。
$input = json_decode($rawBody, true);

// 用 is_array() 判斷剛才有沒有解析成功：
//   成功 → $input 是陣列，直接用它
//   失敗 → 代表這是一般表單送來的，改用 PHP 已經幫我們準備好的 $_POST
// 這樣一支程式就能同時服務 ajax 和傳統表單兩種呼叫方式。
if (!is_array($input)) {
    $input = $_POST;
}

// 取出名為 captcha 的欄位，並做三重防護：
//   isset(...)                    → 對方可能根本沒送這個欄位
//   is_scalar(...)                → 對方可能惡意送一個陣列進來（例如 captcha[]=a&captcha[]=b），
//                                   陣列硬轉成字串會產生警告訊息，警告一旦印出來就會污染回應內容
//   (string) ...                  → 送數字進來時（JSON 的 {"captcha":1234}）先轉成字串，
//                                   確保傳給 captchaVerify() 的型別一定正確
// 任何一關沒過就用空字串代替，而空字串在 captchaVerify() 裡一律判定失敗。
$answer = isset($input['captcha']) && is_scalar($input['captcha']) ? (string) $input['captcha'] : '';


// -----------------------------------------------------------------------------
// 比對並輸出結果
// -----------------------------------------------------------------------------
// captchaVerify() 回傳布林值 true / false，
// 但如果直接 echo 布林值，true 會印出 '1'、false 會印出「空字串」（不是 '0'！），
// 那前端就收不到明確的 0 了。
// 所以這裡用三元運算子明確轉成 '1' 或 '0' 兩個字元。
echo captchaVerify($answer) ? '1' : '0';

exit;
